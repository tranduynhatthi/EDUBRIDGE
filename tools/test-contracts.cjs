// Static contract tests that run without npm dependencies.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname,'..');
const read = name => fs.readFileSync(path.join(root,name),'utf8');
const teacher = read('src/app/builder/page.tsx');
const api = read('src/app/api/ai/lesson/route.ts');
const sql = read('supabase/02_textbook_library.sql');
const books = read('src/app/api/admin/books/route.ts');
const lessonAdmin = read('src/app/api/admin/lessons/route.ts');
const review = read('src/app/api/admin/lessons/[id]/route.ts');
assert(!teacher.includes('type="file"'),'Teacher must not upload PDFs from the single-library page');
assert(!teacher.includes('Tự đưa nội dung SGK'),'Remove teacher-upload selector');
assert(teacher.includes('readyLessonId:selected.id'),'Ready material is selected by database ID');
assert(teacher.includes('textbookLessonId:selected.id'),'Approved SGK is selected by database ID');
assert(teacher.includes(".eq('is_published',true)"),'Approved catalog only');
assert(api.includes('CatalogRequestSchema.safeParse(body)'),'AI endpoint must validate catalog-only requests');
assert(api.includes(".eq('is_published',true)"),'AI endpoint must filter published lessons');
assert(api.includes('ReadyLessonRequestSchema.safeParse(body)'),'Ready library IDs must be validated server-side');
assert(api.includes(".from('edubridge_ready_lessons')"),'Ready lesson content fetched by server');
assert(api.includes(".eq('is_published',true)"),'Catalog mode still requires admin-reviewed content');
assert(api.includes('textbook_lesson_id: data.textbookLessonId'),'Generated lesson records source FK');
assert(books.includes('requireAdmin(request)') && lessonAdmin.includes('requireAdmin(request)') && review.includes('requireAdmin(request)'),'All write endpoints require admin');
assert(sql.includes("'edubridge-textbooks','edubridge-textbooks',false"),'Source PDF must be in PRIVATE bucket');
assert(sql.includes('enable row level security'),'Textbook data must have RLS');
assert(sql.includes('is_published and exists'),'Non-admins can only read published content');
assert(!fs.existsSync(path.join(root,'src/app/api/files/extract/route.ts')),'Old teacher-upload endpoint must be removed');
console.log('PASS: database-first selection and authorized reading of approved/ready material.');

const dashboard=read('src/app/dashboard/page.tsx');
assert(dashboard.includes('Xin chào, {displayName}'),'Greeting must show signed-in teacher name');
assert(dashboard.includes('SUBJECT_GROUPS'),'Dashboard must provide subject buttons');
assert(teacher.includes('value={subject}'),'Teacher must choose a subject');
assert(!teacher.includes('Bộ sách giáo khoa<select'),'Builder must not require book-series selection');
assert(read('src/lib/schema.ts').includes('isValidSubject'),'Legacy source subject validation remains available');
assert(read('src/app/api/ai/lesson/route.ts').includes('subject:custom.data.subject'),'AI must preserve submitted subject');
assert(read('src/app/api/admin/books/route.ts').includes('subject:v.subject'),'Library must persist subject');
console.log('PASS: THPT subjects, personalized home, subject-aware generation and no book-series picker.');
